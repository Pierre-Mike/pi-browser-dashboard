/**
 * "ships the nine sample families" -> "ships the ten sample families".
 *
 * Best-effort, and it returns a note rather than an error when it cannot: the
 * count is in a *test title*, which nothing asserts, so a stale word is a
 * documentation bug and not a red build. Worth doing anyway — every family so far
 * has left one of these behind, and #531 needed a follow-up commit for three.
 */
const countPhrase = (input: { readonly word: string }): string =>
  `the ${input.word} sample families`

const countWord = (input: { readonly count: number }): string => COUNT_WORDS[input.count] ?? ""

export const retitleFamilyCount = (input: {
  readonly source: string
  /**
   * How many daisyUI themes exist *before* this family — two per family, read off
   * `tailwind.config.js`.
   *
   * The arithmetic is in here rather than at the call site because the call site
   * got it wrong: passing the count of existing *families* looked right, left the
   * word one behind, and the generator reported "could not update" while the file
   * still said "nine" for ten families. A number the caller has to derive is a
   * number the caller can derive incorrectly, and no test could see it.
   */
  readonly themesBefore: number
}): { readonly text: string; readonly note: string | null } => {
  const count = input.themesBefore / 2 + 1
  const was = countWord({ count: count - 1 })
  const now = countWord({ count })
  const swappable = was !== "" && now !== "" && input.source.includes(countPhrase({ word: was }))
  return swappable
    ? {
        text: input.source.replaceAll(countPhrase({ word: was }), countPhrase({ word: now })),
        note: null,
      }
    : {
        text: input.source,
        note: "could not update the family count in theme.core.test.ts's title — say the new count by hand",
      }
}
